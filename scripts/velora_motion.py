"""Builds the Velora card animation (a product walkthrough) from Figma screens and writes VeloraMotion.astro.
Usage: python3 velora_motion.py <dir with Figma screenshot blobs> <repo>"""
import sys, glob, os, hashlib, time
from PIL import Image, ImageDraw
B, REPO = sys.argv[1], sys.argv[2]
OUT = f'{REPO}/public/images/case-studies/velora/motion'
URL = '/images/case-studies/velora/motion'
os.makedirs(OUT, exist_ok=True)
for old in glob.glob(OUT + '/*'): os.remove(old)
f = lambda s: Image.open(glob.glob(f'{B}/mcp-Figma-blob-*-{s}.png')[0]).convert('RGB')
W, H, SCALE = 1440, 1024, 1.0

def save(im, name):
    if SCALE != 1: im = im.resize((round(im.width * SCALE), round(im.height * SCALE)), Image.LANCZOS)
    im.save(f'{OUT}/{name}.webp', 'WEBP', quality=88, method=6)

def scene(img, name, tiles):
    base = img.copy(); d = ImageDraw.Draw(base); out = []
    for key, x, y, w, h, kind in tiles:
        fill = img.getpixel((x + w // 2, max(0, y - 4))) if kind != 'bar' else img.getpixel((x + 2, y + 2))
        save(img.crop((x, y, x + w, y + h)), f'{name}-{key}')
        out.append((key, x / W * 100, y / H * 100, w / W * 100, h / H * 100, kind))
        d.rectangle([x, y, x + w - 1, y + h - 1], fill=fill)
    save(base, f'{name}-base')
    return out

S1 = scene(f('fhltg8-4239e690'), 'a',
    [(f'k{i}', x, 96, 398, 102, 'up') for i, x in enumerate([892, 474, 56])] +
    [('m1', 705, 318, 580, 94, 'up'), ('m2', 705, 420, 580, 94, 'up')] +
    [(f't{i}', 56, 321 + i * 130, 585, 122, 'up') for i in range(5)])
S2 = scene(f('km8xj3-2e47331f'), 'b', [
    ('s1', 684, 270, 606, 110, 'up'), ('s2', 56, 270, 606, 110, 'up'),
    ('inc', 682, 398, 608, 268, 'up'), ('don', 56, 398, 608, 268, 'up'), ('goals', 56, 684, 1234, 322, 'up')])
S3 = scene(f('8gemce-3201bef1'), 'c', [(f'b{i}', x, 600, 122, 272, 'bar') for i, x in enumerate([1060, 830, 600, 370, 140])])

V = hashlib.md5(str(time.time()).encode()).hexdigest()[:8]
DUR = 14
def layer(prefix, tiles, n):
    imgs = '\n'.join(f'        <img class="tile k-{kind} s{n}" style="left:{x:.3f}%;top:{y:.3f}%;width:{w:.3f}%;height:{h:.3f}%;--i:{i}" src="{URL}/{prefix}-{key}.webp?v={V}" alt="" loading="lazy" decoding="async" />'
                     for i, (key, x, y, w, h, kind) in enumerate(tiles))
    return f'''      <div class="scene scene--{n}">
        <img class="base" src="{URL}/{prefix}-base.webp?v={V}" alt="" loading="lazy" decoding="async" />
{imgs}
      </div>'''

