"""Builds the layered Money Map card animation from three Figma phone screens and writes MoneyMapMotion.astro.
Usage: python3 money_map_motion.py <dir with Figma screenshot blobs> <repo>"""
import sys, glob, os
from PIL import Image, ImageDraw
B, REPO = sys.argv[1], sys.argv[2]
OUT = f'{REPO}/public/images/case-studies/the-money-map/motion'
URL = '/images/case-studies/the-money-map/motion'
os.makedirs(OUT, exist_ok=True)
for old in glob.glob(OUT + '/*'): os.remove(old)
f = lambda s: Image.open(glob.glob(f'{B}/mcp-Figma-blob-*-{s}.png')[0]).convert('RGB')
SCALE = 2.0  # screens are 390 wide at 1x; phone is ~260px wide in the card, so 2x keeps it sharp
PH = 844     # visible phone height

def save(im, name):
    im = im.resize((round(im.width * SCALE), round(im.height * SCALE)), Image.LANCZOS)
    im.save(f'{OUT}/{name}.webp', 'WEBP', quality=88, method=6)

def scene(img, name, tiles):
    img = img.crop((0, 0, 390, PH))
    base = img.copy(); d = ImageDraw.Draw(base); out = []
    for key, x, y, w, h, kind in tiles:
        fill = img.getpixel((x + w // 2, max(0, y - 4)))
        save(img.crop((x, y, x + w, y + h)), f'{name}-{key}')
        out.append((key, x / 390 * 100, y / PH * 100, w / 390 * 100, h / PH * 100, kind))
        d.rectangle([x, y, x + w - 1, y + h - 1], fill=fill)
    save(base, f'{name}-base')
    return out

S1 = scene(f('7pznkt-f5b7c639'), 'a', [
    ('hi', 20, 95, 350, 22, 'up'), ('hero', 20, 123, 350, 290, 'up'),
    ('r1', 20, 421, 350, 68, 'up'), ('r2', 20, 497, 350, 68, 'up'), ('r3', 20, 573, 350, 68, 'up'), ('r4', 20, 649, 350, 64, 'up'),
    ('nav', 20, 714, 350, 66, 'up')])
S2 = scene(f('esh66v-76e1a310'), 'b', [
    ('days', 0, 93, 390, 42, 'right'), ('tabs', 20, 149, 350, 46, 'up'), ('video', 20, 211, 350, 503, 'up'), ('nav', 20, 714, 350, 66, 'up')])
S3 = scene(f('3dle3d-73d5dc88'), 'c', [
    ('tabs', 18, 95, 352, 46, 'up'), ('total', 46, 173, 298, 104, 'up'),
    ('b1', 46, 461, 62, 37, 'bar'), ('b2', 125, 445, 62, 53, 'bar'), ('b3', 204, 391, 62, 107, 'bar'), ('b4', 282, 300, 62, 198, 'bar'),
    ('h', 186, 596, 184, 24, 'up'), ('l1', 22, 634, 346, 56, 'up'), ('l2', 22, 698, 346, 56, 'up'), ('l3', 22, 762, 346, 56, 'up')])

DUR = 14
def layer(prefix, tiles, n):
    imgs = '\n'.join(f'        <img class="tile k-{kind} s{n}" style="left:{x:.3f}%;top:{y:.3f}%;width:{w:.3f}%;height:{h:.3f}%;--i:{i}" src="{URL}/{prefix}-{key}.webp" alt="" loading="lazy" decoding="async" />'
                     for i, (key, x, y, w, h, kind) in enumerate(tiles))
    return f'''      <div class="scene scene--{n}"><div class="cam cam--{n}">
        <img class="base" src="{URL}/{prefix}-base.webp" alt="" loading="lazy" decoding="async" />
{imgs}
      </div></div>'''

extra = '\n        <span class="pulse"></span>'
s2 = layer('b', S2, 2).replace('      </div></div>', extra + '\n      </div></div>')

html = f'''---
/**
 * Animated card preview for The Money Map, generated by scripts/money_map_motion.py from the Figma screens.
 * One phone, three scenes: the day-1 map builds and zooms into the task card, the daily video lesson
 * zooms into play, and the savings screen grows its bars. Transparent image layers, not video.
 */
---
<div class="motion motion--mm" aria-hidden="true">
  <div class="rig"><div class="dev">
{layer('a', S1, 1)}
{s2}
{layer('c', S3, 3)}
  </div></div>
</div>

<style>
  .motion {{ position: absolute; inset: 0; container-type: inline-size; pointer-events: none; opacity: 0; transition: opacity .35s ease; }}
  .rig {{ position: absolute; left: 35.5cqw; top: 2.9cqw; width: 29cqw; aspect-ratio: 390 / 844; }}
  .dev {{
    position: absolute; inset: 0;
    overflow: hidden; background: #f4f4f4; opacity: 0; border-radius: 4.2cqw;
    border: .45cqw solid rgba(255, 255, 255, .75); background-clip: padding-box;
    box-shadow: 2.1cqw 1.7cqw 4.7cqw rgba(112, 144, 176, .2);
  }}
  .scene, .cam {{ position: absolute; inset: 0; }}
  .scene {{ opacity: 0; }}
  .base, .tile {{ position: absolute; display: block; }}
  .base {{ inset: 0; width: 100%; height: 100%; }}
  .tile {{ opacity: 0; }}
  .pulse {{
    position: absolute; left: 50%; top: 57.2%; width: 17%; aspect-ratio: 1; border-radius: 50%;
    border: .5cqw solid #fff; transform: translate(-50%, -50%) scale(.6); opacity: 0;
  }}

  :global(.card.is-playing) .motion--mm {{ opacity: 1; }}
  :global(.card.is-playing .card-static) {{ opacity: 0; }}

  /* the phone rises in once and stays; scenes slide in from the side like app navigation */
  :global(.card.is-playing) .dev {{ animation: dev {DUR}s cubic-bezier(.2,.7,.2,1) infinite; }}
  @keyframes dev {{ 0% {{ opacity: 0; transform: translateY(4cqw) scale(.96); }} 4%, 97% {{ opacity: 1; transform: none; }} 100% {{ opacity: 0; transform: scale(1.02); }} }}
  :global(.card.is-playing) .scene--1 {{ animation: sc1 {DUR}s cubic-bezier(.2,.7,.2,1) infinite; }}
  :global(.card.is-playing) .scene--2 {{ animation: sc2 {DUR}s cubic-bezier(.2,.7,.2,1) infinite; }}
  :global(.card.is-playing) .scene--3 {{ animation: sc3 {DUR}s cubic-bezier(.2,.7,.2,1) infinite; }}
  @keyframes sc1 {{ 0%, 31% {{ opacity: 1; transform: none; }} 34%, 100% {{ opacity: 0; transform: translateX(-8%); }} }}
  @keyframes sc2 {{ 0%, 31% {{ opacity: 0; transform: translateX(10%); }} 34%, 64% {{ opacity: 1; transform: none; }} 67%, 100% {{ opacity: 0; transform: translateX(-8%); }} }}
  @keyframes sc3 {{ 0%, 64% {{ opacity: 0; transform: translateX(10%); }} 67%, 100% {{ opacity: 1; transform: none; }} }}

  /* builds: each scene's parts arrive one after another */
  :global(.card.is-playing) .s1 {{ animation: in1 {DUR}s cubic-bezier(.2,.7,.2,1) infinite; animation-delay: calc(.35s + var(--i) * .15s); }}
  :global(.card.is-playing) .s2 {{ animation: in2 {DUR}s cubic-bezier(.2,.7,.2,1) infinite; animation-delay: calc(var(--i) * .15s); }}
  :global(.card.is-playing) .s3 {{ animation: in3 {DUR}s cubic-bezier(.2,.7,.2,1) infinite; animation-delay: calc(var(--i) * .13s); }}
  :global(.card.is-playing) .k-right {{ animation-name: in2r; }}
  :global(.card.is-playing) .k-bar {{ transform-origin: 50% 100%; animation-name: in3b; }}
  @keyframes in1  {{ 0% {{ opacity: 0; transform: translateY(16%) scale(.97); }} 3%, 30% {{ opacity: 1; transform: none; }} 34%, 100% {{ opacity: 0; }} }}
  @keyframes in2  {{ 0%, 33% {{ opacity: 0; transform: translateY(16%) scale(.97); }} 36%, 63% {{ opacity: 1; transform: none; }} 67%, 100% {{ opacity: 0; }} }}
  @keyframes in2r {{ 0%, 33% {{ opacity: 0; transform: translateX(30%); }} 37%, 63% {{ opacity: 1; transform: none; }} 67%, 100% {{ opacity: 0; }} }}
  @keyframes in3  {{ 0%, 66% {{ opacity: 0; transform: translateY(16%) scale(.97); }} 69%, 99% {{ opacity: 1; transform: none; }} 100% {{ opacity: 0; }} }}
  @keyframes in3b {{ 0%, 68% {{ opacity: 0; transform: scaleY(0); }} 69% {{ opacity: 1; transform: scaleY(0); }} 73%, 99% {{ opacity: 1; transform: none; }} 100% {{ opacity: 0; }} }}

  /* the whole phone, frame included, zooms: into the day-1 card, onto the play button, then onto the savings chart */
  :global(.card.is-playing) .rig {{ animation: zoom {DUR}s cubic-bezier(.45,0,.2,1) infinite; }}
  @keyframes zoom {{
    0%, 17% {{ transform: none; transform-origin: 50% 32%; }}
    23%, 29% {{ transform: scale(1.45); transform-origin: 50% 32%; }}
    33%, 46% {{ transform: none; transform-origin: 50% 57%; }}
    52%, 62% {{ transform: scale(1.6); transform-origin: 50% 57%; }}
    66%, 82% {{ transform: none; transform-origin: 50% 40%; }}
    88%, 97% {{ transform: scale(1.35); transform-origin: 50% 40%; }}
    100% {{ transform: none; transform-origin: 50% 40%; }}
  }}
  :global(.card.is-playing) .pulse {{ animation: pulse {DUR}s ease-out infinite; }}
  @keyframes pulse {{ 0%, 53% {{ opacity: 0; transform: translate(-50%, -50%) scale(.6); }} 54% {{ opacity: .9; }} 60% {{ opacity: 0; transform: translate(-50%, -50%) scale(1.5); }} 61%, 100% {{ opacity: 0; }} }}

  @media (prefers-reduced-motion: reduce) {{ .motion {{ display: none; }} }}
</style>

<script>
  const cards = document.querySelectorAll<HTMLElement>('.card:has(.motion--mm)');
  if (!matchMedia('(prefers-reduced-motion: reduce)').matches) {{
    if (matchMedia('(hover: hover)').matches) {{
      cards.forEach((c) => {{
        const on = () => c.classList.add('is-playing');
        const off = () => c.classList.remove('is-playing');
        c.addEventListener('mouseenter', on); c.addEventListener('mouseleave', off);
        c.addEventListener('focusin', on); c.addEventListener('focusout', off);
      }});
    }} else {{
      const io = new IntersectionObserver((es) => es.forEach((e) => e.target.classList.toggle('is-playing', e.isIntersecting)), {{ threshold: 0.6 }});
      cards.forEach((c) => io.observe(c));
    }}
  }}
</script>
'''
open(f'{REPO}/src/components/MoneyMapMotion.astro', 'w').write(html)
print(len(glob.glob(OUT + '/*')), 'files')
