"""Builds the layered Cover card animation: crops UI parts from the Figma screens and writes CoverMotion.astro."""
import sys, glob, os, hashlib, time
from PIL import Image, ImageDraw
B, REPO = sys.argv[1], sys.argv[2]
OUT = f'{REPO}/public/images/case-studies/cover/motion'
os.makedirs(OUT, exist_ok=True)
for old in glob.glob(OUT + '/*'): os.remove(old)
f = lambda s: Image.open(glob.glob(f'{B}/mcp-Figma-blob-*-{s}.png')[0]).convert('RGB')
URL = '/images/case-studies/cover/motion'

def save(im, name, maxw=None):
    if maxw and im.width > maxw: im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    im.save(f'{OUT}/{name}.webp', 'WEBP', quality=88, method=6)

def scene(img, name, tiles, bg, scale):
    """tiles: list of (key, x, y, w, h) in screen px. Writes base (tiles erased) + one crop per tile."""
    W, H = img.size
    base = img.copy(); d = ImageDraw.Draw(base)
    out = []
    for key, x, y, w, h in tiles:
        d.rectangle([x, y, x + w - 1, y + h - 1], fill=bg)
        save(img.crop((x, y, x + w, y + h)), f'{name}-{key}', maxw=round(w * scale))
        out.append((key, x / W * 100, y / H * 100, w / W * 100, h / H * 100))
    save(base, f'{name}-base', maxw=round(W * scale))
    return out

